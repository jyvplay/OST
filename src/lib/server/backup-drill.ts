// Selection is repeatable for the same bundle but is not a security sampling guarantee.
export const DRILL_LIMITS = { files: 12, folders: 8, notes: 8, settings: 12 } as const;

function pick<T>(items: T[], count: number, digest: string, tag: string, identity: (v: T, i: number) => string): T[] {
  return items.map((item, i) => ({ item, i, score: sha256(`${digest}\0${tag}\0${identity(item, i)}`) }))
    .sort((a, b) => a.score.localeCompare(b.score) || a.i - b.i).slice(0, count).map(({ item }) => item);
}

export function sampleBackup(payload: BackupPayload, digest: string): BackupPayload {
  const files = pick(payload.entries.filter((e) => e.kind === "file"), DRILL_LIMITS.files, digest, "file", (e) => e.path);
  const folders = pick(payload.entries.filter((e) => e.kind === "dir"), DRILL_LIMITS.folders, digest, "folder", (e) => e.path);
  const sampledNotes = pick(payload.notes, DRILL_LIMITS.notes, digest, "note", (_n, i) => String(i));
  const sampledSettings = pick(payload.settings, DRILL_LIMITS.settings, digest, "setting", (s) => s.key);
  return { ...payload, entries: [...folders, ...files], notes: sampledNotes, settings: sampledSettings };
}

/*
 * Only literal, audited defaults are installed in temp tables: LIKE's copied serial
 * defaults would otherwise advance production sequences (nextval is not rolled back).
 * Indexes and NOT NULL/primary-key constraints are copied, but PostgreSQL LIKE does
 * not copy triggers or foreign keys. Schema drift should fail the drill, not write to
 * an unshadowed relation. A rollback also drops all temp tables and identity sequences.
 */
const TABLES: Record<string, Record<string, string>> = {
  vfs_nodes: { parent: "'/'", mime: "'application/octet-stream'", encoding: "'utf8'", content: "''", size: "0", sha256: "''", tags: "''", trashed: "false", version: "1", created_at: "pg_catalog.now()", updated_at: "pg_catalog.now()" },
  vfs_versions: { encoding: "'utf8'", content: "''", size: "0", sha256: "''", reason: "'write'", created_at: "pg_catalog.now()" },
  file_ops: { src: "''", dst: "''", state: "'REQUESTED'", bytes: "0", sha256: "''", error: "''", steps: "'[]'::jsonb", created_at: "pg_catalog.now()", updated_at: "pg_catalog.now()" },
  settings: { category: "'general'", label: "''", aliases: "''", lock_reason: "''", updated_at: "pg_catalog.now()" },
  settings_history: { old_value: "''", new_value: "''", created_at: "pg_catalog.now()" },
  notes: { title: "'Untitled'", body: "''", tags: "''", pinned: "false", created_at: "pg_catalog.now()", updated_at: "pg_catalog.now()" },
  index_docs: { body: "''", updated_at: "pg_catalog.now()" },
  audit_log: { actor: "'user'", detail: "''", created_at: "pg_catalog.now()" },
};

async function makeScratchTables(tx: TransactionDb) {
  // Resolve every source before creating any shadow, and refuse a previously leaked
  // temp relation, a view, or an absent table. No untrusted identifiers are interpolated.
  const sources: { table: string; schema: string }[] = [];
  for (const table of Object.keys(TABLES)) {
    const result = await tx.execute(sql`SELECT n.nspname AS schema, c.relkind AS kind,
      n.oid = pg_catalog.pg_my_temp_schema() AS is_temp
      FROM pg_catalog.pg_class c JOIN pg_catalog.pg_namespace n ON n.oid = c.relnamespace
      WHERE c.oid = pg_catalog.to_regclass(${table})`);
    const row = result.rows[0] as { schema?: string; kind?: string; is_temp?: boolean } | undefined;
    if (!row?.schema || row.is_temp || (row.kind !== "r" && row.kind !== "p")) throw new RestoreError("Cannot prepare isolated scratch tables for this database schema.", 503);
    sources.push({ table, schema: row.schema });
  }
  for (const { table, schema } of sources) {
    await tx.execute(sql`CREATE TEMP TABLE ${sql.identifier(table)} (LIKE ${sql.identifier(schema)}.${sql.identifier(table)} INCLUDING ALL EXCLUDING DEFAULTS) ON COMMIT DROP`);
    if (table !== "settings") {
      // All current IDs are serial integers. If a future schema has its own identity,
      // or does not match this assumption, fail closed instead of using a shared sequence.
      await tx.execute(sql`ALTER TABLE pg_temp.${sql.identifier(table)} ALTER COLUMN id ADD GENERATED BY DEFAULT AS IDENTITY`);
    }
    for (const [column, expression] of Object.entries(TABLES[table])) {
      await tx.execute(sql`ALTER TABLE pg_temp.${sql.identifier(table)} ALTER COLUMN ${sql.identifier(column)} SET DEFAULT ${sql.raw(expression)}`);
    }
  }
  // No public fallback for an accidental new unqualified table reference.
  await tx.execute(sql`SET LOCAL search_path = pg_temp, pg_catalog`);
}

export interface DrillResult {
  kind: "data" | "config";
  sampled: { files: number; folders: number; notes: number; settings: number };
  total: { files: number; folders: number; notes: number; settings: number };
  skippedSettings: number;
}

/**
 * Restore a bounded sample through the SAME preview/apply engine into isolated real
 * PostgreSQL temporary tables; read data and indexes back before an acknowledged rollback.
 * All source rows are validated by the caller first. This tests neither remote storage,
 * long-term retention, other devices nor unlocking encrypted Private-volume contents.
 */
export async function drillBackup(payload: BackupPayload, digest: string, source?: Pick<Pool, "connect">): Promise<DrillResult> {
  const sample = sampleBackup(payload, digest);
  const count = (p: BackupPayload) => ({ files: p.entries.filter((e) => e.kind === "file").length,
    folders: p.entries.filter((e) => e.kind === "dir").length, notes: p.notes.length, settings: p.settings.length });
  const sampled = count(sample), total = count(payload);
  if (!sampled.files && !sampled.folders && !sampled.notes && !sampled.settings) throw new RestoreError("This backup is empty; there is nothing to restore in a drill.", 422);

  return safeTransaction(async (tx) => {
    const keys = sample.settings.map((item) => item.key);
    const sourceSettings = keys.length ? await tx.select({ key: settings.key, lockReason: settings.lockReason }).from(settings).where(inArray(settings.key, keys)) : [];
    await makeScratchTables(tx);
    // Use artificial values so unchanged settings still exercise the actual write path.
    for (const row of sourceSettings) {
      const value = sample.settings.find((s) => s.key === row.key)!.value;
      const sentinel = value === "__fusion_drill_scratch__" ? "__fusion_drill_scratch_2__" : "__fusion_drill_scratch__";
      await tx.insert(settings).values({ key: row.key, value: sentinel, lockReason: row.lockReason });
    }
    const preview = await restoreInTransaction(tx, sample, digest, true);
    const applied = await restoreInTransaction(tx, sample, digest, false, preview.previewToken);
    const skippedSettings = applied.summary.settingsLocked.length + applied.summary.settingsUnknown.length;
    if (sampled.settings && !sampled.files && !sampled.folders && !sampled.notes && skippedSettings === sampled.settings) {
      throw new RestoreError("None of the sampled settings can be restored on this server.", 422);
    }

    const rows = await tx.select().from(vfsNodes);
    const nodes = new Map(rows.map((row) => [row.path, row]));
    const idx = await tx.select().from(indexDocs);
    const index = new Map(idx.map((row) => [`${row.source}\0${row.ref}`, row]));
    const fail = () => { throw new RestoreError("Scratch restore read-back did not match the selected sample.", 409); };
    for (const e of sample.entries) {
      const n = nodes.get(e.path);
      if (!n || n.kind !== e.kind || n.trashed || n.mime !== e.mime || n.tags !== e.tags) fail();
      if (e.kind === "file") {
        if (!n || n.encoding !== e.encoding || n.content !== e.content || n.size !== e.size || n.sha256 !== e.sha256 || sha256(n.content) !== e.sha256) fail();
        const found = index.get(`file\0${e.path}`);
        const expectedBody = isTextual(e.mime) && e.encoding === "utf8" ? e.content.slice(0, 50_000) : "";
        if (isPrivateVfsPath(e.path) ? !!found : !found || found.title !== baseName(e.path) || found.body !== expectedBody) fail();
      }
    }
    const savedNotes = await tx.select().from(notes);
    const noteKey = (n: { title: string; body: string; tags: string; pinned: boolean; createdAt: string; updatedAt: string }) => canonicalJson(n);
    const expectedNotes = sample.notes.map(noteKey).sort();
    const actualNotes = savedNotes.map((n) => noteKey({ title: n.title, body: n.body, tags: n.tags, pinned: n.pinned,
      createdAt: n.createdAt.toISOString(), updatedAt: n.updatedAt.toISOString() })).sort();
    if (canonicalJson(expectedNotes) !== canonicalJson(actualNotes)) fail();
    for (const note of savedNotes) {
      const found = index.get(`note\0${note.id}`);
      if (!found || found.title !== note.title || found.body !== note.body) fail();
    }
    const savedSettings = new Map((await tx.select().from(settings)).map((s) => [s.key, s]));
    for (const item of sample.settings) {
      const row = savedSettings.get(item.key);
      if (row && !row.lockReason && row.value !== item.value) fail();
    }
    const journals = await tx.select().from(fileOps);
    const audits = await tx.select().from(auditLog);
    if (journals.length !== 1 || journals[0].state !== "COMPLETE" || journals[0].sha256 !== digest || audits.length !== 1 || audits[0].action !== "backup.restore") fail();
    return { kind: payload.kind, sampled, total, skippedSettings };
  }, { isolationLevel: "serializable", rollbackOnly: true }, source);
}
