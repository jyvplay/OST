#!/usr/bin/env bash
# TT62: fetches the ECMA-376 transitional XSDs used by scripts/oracle/ooxml_xsd.py (TEST-ONLY data, not committed).
# Source: github.com/python-openxml/python-docx, ref/xsd (MIT repository; the schemas themselves are Ecma's ECMA-376
# transitional set, freely usable). Pinned to a commit so the oracle is reproducible. Uses the GitHub contents API via
# `gh` (raw.githubusercontent.com is not reachable from every sandbox).
# Usage: bash scripts/oracle/fetch-xsd.sh [DEST]   (default $OOXML_XSD or /home/user/tools/xsd)
set -euo pipefail
REF=e45454602b53e8e572b179ccf1c91093ec9f4ed7
DEST=${1:-${OOXML_XSD:-/home/user/tools/xsd}}
mkdir -p "$DEST/opc"
get() { # repo path → file
  gh api -H "Accept: application/vnd.github.raw" "repos/python-openxml/python-docx/contents/$1?ref=$REF" > "$2.tmp" && mv "$2.tmp" "$2"
}
for f in $(gh api "repos/python-openxml/python-docx/contents/ref/xsd?ref=$REF" --jq '.[] | select(.type=="file") | .name'); do get "ref/xsd/$f" "$DEST/$f"; done
for f in $(gh api "repos/python-openxml/python-docx/contents/ref/xsd/opc-xsd?ref=$REF" --jq '.[] | select(.type=="file") | .name'); do get "ref/xsd/opc-xsd/$f" "$DEST/opc/$f"; done
# sanity: the two schemas the Office gates depend on
grep -q 'targetNamespace="http://schemas.openxmlformats.org/wordprocessingml/2006/main"' "$DEST/wml.xsd"
grep -q 'targetNamespace="http://schemas.openxmlformats.org/spreadsheetml/2006/main"' "$DEST/sml.xsd"
echo "XSDs in $DEST ($(ls "$DEST"/*.xsd "$DEST"/opc/*.xsd | wc -l) files); _xml.xsd is generated by ooxml_xsd.py on first use"
