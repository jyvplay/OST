#!/usr/bin/env node
/**
 * TT20 — Tails side-by-side ledger generator + validator.
 * Reads scripts/tails-features.json, checks every cited test against docs/test-results/*.json
 * (each [suite, nameSubstring] must match ≥1 recorded test and every match must have passed),
 * enforces: full ⇒ ≥1 evidence; none ⇒ a reason; partial ⇒ a reason. Writes docs/TAILS-COMPARISON.md.
 * Exit 1 on any violation. Run: node scripts/tails-ledger.mjs
 */
import { readFileSync, readdirSync, writeFileSync } from "node:fs";

const data = JSON.parse(readFileSync("scripts/tails-features.json", "utf8"));
const results = {};
for (const f of readdirSync("docs/test-results")) {
  const j = JSON.parse(readFileSync(`docs/test-results/${f}`, "utf8"));
  results[j.suite] = { at: j.at, tests: j.results };
}
const problems = [];
const evid = (row) => (row.evidence ?? []).map(([suite, sub]) => {
  const s = results[suite];
  if (!s) { problems.push(`${row.id}: suite ${suite} has no recorded results`); return `✗ ${suite}`; }
  const hits = s.tests.filter((t) => t.name.includes(sub));
  if (!hits.length) { problems.push(`${row.id}: no test in ${suite} matches "${sub}"`); return `✗ ${suite} "${sub}"`; }
  const failed = hits.filter((t) => !t.pass);
  if (failed.length) problems.push(`${row.id}: ${failed.length} cited test(s) in ${suite} failed`);
  return `${failed.length ? "✗" : "✓"} ${suite}${sub ? ` "${sub}"` : ` (all ${hits.length})`}`;
});
const ids = new Set();
const lines = data.rows.map((r) => {
  if (ids.has(r.id)) problems.push(`duplicate ${r.id}`); ids.add(r.id);
  if (!["none", "partial", "full"].includes(r.status)) problems.push(`${r.id}: bad status ${r.status}`);
  if (r.status === "full" && !(r.evidence ?? []).length) problems.push(`${r.id}: full without evidence`);
  if (r.status !== "full" && !r.why) problems.push(`${r.id}: ${r.status} without a reason`);
  const e = evid(r);
  const esc = (s) => String(s ?? "").replace(/\|/g, "\\|");
  return `| ${r.id} | ${esc(r.area)} | ${esc(r.tails)} | ${esc(r.fusion)} | **${r.status}** | ${esc(e.join("<br>") || "—")} | ${esc(r.why ?? r.note ?? "")} |`;
});
for (const p of data.painPoints) for (const id of p.rows) if (!ids.has(id)) problems.push(`${p.id}: unknown row ${id}`);
const count = (st, area) => data.rows.filter((r) => r.status === st && (area ? r.area === area : true)).length;
const tailsRows = data.rows.filter((r) => r.area !== "Beyond Tails");
const tc = (st) => tailsRows.filter((r) => r.status === st).length;
const md = `# Tails ↔ Fusion Shell — side-by-side ledger

_Generated by \`node scripts/tails-ledger.mjs\` from \`scripts/tails-features.json\`; every cited test is checked against
\`docs/test-results/*.json\` (must exist and pass). Generated ${new Date().toISOString().slice(0, 10)}._

**Status:** full = equivalent protection implemented **and** cited tests pass · partial = narrower analogue or
untested equivalence · none = not built (reason given).

**Tails features (${tailsRows.length}):** full **${tc("full")}** · partial **${tc("partial")}** · none **${tc("none")}**.
**Beyond Tails (${count("full", "Beyond Tails") + count("partial", "Beyond Tails")}):** features Tails does not have.

The honest headline: Fusion matches or beats Tails on the *encrypted storage, amnesia, metadata and backup* surface, and has
**nothing** on the *network anonymity* surface (Tor, bridges, MAC spoofing, OnionShare). A web app cannot control the network
stack, and it runs on top of the host OS instead of replacing it (T39).

| # | Area | Tails | Fusion Shell | Status | Evidence (suite "test") | Gap / reason |
|---|---|---|---|---|---|---|
${lines.join("\n")}

## Shared limits (parity of a weakness — not counted)
${data.sharedLimits.map((s) => `- ${s}`).join("\n")}

## Tails pain points (web/Reddit) and what Fusion does about them

| # | Pain point | Sources | Fusion answer | Status | Rows |
|---|---|---|---|---|---|
${data.painPoints.map((p) => `| ${p.id} | ${p.pain} | ${p.sources.map((u, i) => `[${i + 1}](${u})`).join(" ")} | ${p.ours}${p.why ? ` _(gap: ${p.why})_` : ""} | **${p.status}** | ${p.rows.join(", ")} |`).join("\n")}
`;
writeFileSync("docs/TAILS-COMPARISON.md", md);
console.log(`Tails rows ${tailsRows.length}: full ${tc("full")} / partial ${tc("partial")} / none ${tc("none")}; beyond-Tails ${data.rows.length - tailsRows.length}; pain points ${data.painPoints.length}`);
if (problems.length) { console.error(problems.map((p) => `  ✗ ${p}`).join("\n")); process.exit(1); }
console.log("all cited evidence present and passing → docs/TAILS-COMPARISON.md");
